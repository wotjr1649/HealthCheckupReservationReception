'use strict';
// 7 — P02-05 예약 조회 · P02-07 예약 취소.
// P02-05 는 P03-04 와 동일한 업무 데이터를 조회하며 실제 Form/SP 를 공유한다 — 이 결정을 강조한다.
const { A, node, gate, term, sub, head, note, ar, elab, elabN, S } = require('../flow');

const Q = [0.46, 1.99, 3.52, 5.05], QW = 1.30;
const qcx = i => Q[i] + QW / 2, qr = i => Q[i] + QW;
const K = [6.66, 8.28, 9.90, 11.52], KW = 1.30;
const kcx = i => K[i] + KW / 2, kr = i => K[i] + KW;
const R = [1.42, 2.22, 3.02], H = 0.56;
const ry = i => R[i] + H / 2, rb = i => R[i] + H;
const NS = { size: 8 };

function draw(c) {
  // ── P02-05 예약 조회 ─────────────────────────────────────────────
  head(c, A.x, 1.08, 5.90, 'P02-05  예약 조회', { h: 0.24 });
  term(c, Q[0], R[0], QW, H, '예약 조회 시작', NS);
  node(c, Q[1], R[0], QW, H, '조회조건 입력', NS);
  node(c, Q[2], R[0], QW, H, '예약·접수 공통\n업무내역 조회', NS);
  gate(c, Q[3], R[0], QW, H, '결과 존재?', NS);
  term(c, Q[1], R[1], QW, H, '조회 결과 없음', NS);
  term(c, Q[2], R[1], QW, H, '조회 완료', NS);
  node(c, Q[3], R[1], QW, H, '업무 건 선택 /\n상세 확인', NS);

  ar(c, [[qr(0), ry(0)], [Q[1] - 0.03, ry(0)]]);
  ar(c, [[qr(1), ry(0)], [Q[2] - 0.03, ry(0)]]);
  ar(c, [[qr(2), ry(0)], [Q[3] - 0.03, ry(0)]]);
  ar(c, [[qcx(3), rb(0)], [qcx(3), R[1] - 0.03]]);
  elab(c, qcx(3) + 0.24, (rb(0) + R[1]) / 2, 'Yes');
  ar(c, [[Q[3], ry(1)], [qr(2) + 0.03, ry(1)]]);
  ar(c, [[qcx(3) - 0.38, rb(0)], [qcx(3) - 0.38, 2.09], [qcx(1), 2.09], [qcx(1), R[1] - 0.03]]);
  elab(c, qcx(1) + 0.40, 2.09, 'No');

  // ── P02-07 예약 취소 ─────────────────────────────────────────────
  head(c, 6.66, 1.08, A.r - 6.66, 'P02-07  예약 취소', { h: 0.24 });
  term(c, K[0], R[0], KW, H, '예약 취소 시작', NS);
  sub(c, K[1], R[0], KW, H, 'P02-05\n예약 조회', NS);
  gate(c, K[2], R[0], KW, H, '취소 대상 선택?', NS);
  term(c, K[3], R[0], KW, H, '취소 대상 없음', NS);

  gate(c, K[0], R[1], KW, H, '취소 진행?', NS);
  node(c, K[1], R[1], KW, H, '예약 취소 확인', NS);
  gate(c, K[2], R[1], KW, H, '현재 상태 = RSV?', NS);
  term(c, K[3], R[1], KW, H, '예약 취소 불가', NS);

  term(c, K[0], R[2], KW, H, '예약 취소 중단', NS);
  node(c, K[1], R[2], KW, H, '동시성·현재상태\n최종검증', NS);
  node(c, K[2], R[2], KW, H, '동일 업무 행을\nCNR로 변경', NS);
  term(c, K[3], R[2], KW, H, '예약 취소 완료', NS);

  ar(c, [[kr(0), ry(0)], [K[1] - 0.03, ry(0)]]);
  ar(c, [[kr(1), ry(0)], [K[2] - 0.03, ry(0)]]);
  ar(c, [[kr(2), ry(0)], [K[3] - 0.03, ry(0)]]);
  elab(c, (kr(2) + K[3]) / 2, ry(0), 'No');
  ar(c, [[kcx(2), rb(0)], [kcx(2), R[1] - 0.03]]);
  elab(c, kcx(2) + 0.24, (rb(0) + R[1]) / 2, 'Yes');
  ar(c, [[kr(2), ry(1)], [K[3] - 0.03, ry(1)]]);
  elab(c, (kr(2) + K[3]) / 2, ry(1), 'No');
  ar(c, [[K[2], ry(1)], [kr(1) + 0.03, ry(1)]]);
  elab(c, (K[2] + kr(1)) / 2, ry(1), 'Yes');
  ar(c, [[K[1], ry(1)], [kr(0) + 0.03, ry(1)]]);
  ar(c, [[kcx(0), rb(1)], [kcx(0), R[2] - 0.03]]);
  elab(c, kcx(0) - 0.24, (rb(1) + R[2]) / 2, 'No');
  ar(c, [[kcx(0) + 0.38, rb(1)], [kcx(0) + 0.38, 2.89], [kcx(1), 2.89], [kcx(1), R[2] - 0.03]]);
  elab(c, kcx(0) + 0.66, 2.89, 'Yes');
  ar(c, [[kr(1), ry(2)], [K[2] - 0.03, ry(2)]]);
  ar(c, [[kr(2), ry(2)], [K[3] - 0.03, ry(2)]]);

  // ── 공통 조회 : P02-05 ↔ P03-04 Form/SP 공유 ─────────────────────
  head(c, A.x, 3.86, A.w, '공통 조회   —   P02-05는 P03-04와 동일한 업무 데이터를 조회하며 실제 Form/SP를 공유한다.');
  node(c, 1.10, 4.24, 2.60, 0.46, 'P02-05  예약 조회', { size: 10 });
  node(c, 1.10, 4.90, 2.60, 0.46, 'P03-04  접수 조회', { size: 10 });
  const SX = 4.70, SW = 3.90, SY = 4.36, SH = 0.88;
  node(c, SX, SY, SW, SH, '예약·접수 공통 업무내역 조회\n동일 Form / SP 공유', { size: 10, bold: true, sw: S.W.win });
  c.zone(SX - 0.10, SY - 0.10, SW + 0.20, SH + 0.20);
  ar(c, [[3.70, 4.47], [4.30, 4.47], [4.30, 4.80], [SX - 0.03, 4.80]]);
  ar(c, [[3.70, 5.13], [4.30, 5.13], [4.30, 4.80], [SX - 0.03, 4.80]]);
  node(c, 9.60, 4.24, 3.27, 0.46, 'Context = 예약  →  예약 Ribbon Action', { size: 10 });
  node(c, 9.60, 4.90, 3.27, 0.46, 'Context = 접수  →  접수 Ribbon Action', { size: 10 });
  ar(c, [[SX + SW, 4.80], [9.20, 4.80], [9.20, 4.47], [9.57, 4.47]]);
  ar(c, [[SX + SW, 4.80], [9.20, 4.80], [9.20, 5.13], [9.57, 5.13]]);

  // ── 적용 규칙 ────────────────────────────────────────────────────
  head(c, A.x, 5.62, 6.10, 'P02-05  적용 규칙', { h: 0.24 });
  note(c, A.x, 5.92, 6.10, [
    '· RSV/RCP/CNR/CNC를 모두 조회할 수 있다.',
    '· 후속 변경·취소·접수는 WorkId로 최신 데이터를 다시 조회한 후 상태를 재판정한다.',
  ], { size: 9.5 });
  head(c, 6.77, 5.62, A.r - 6.77, 'P02-07  적용 규칙', { h: 0.24 });
  note(c, 6.77, 5.92, A.r - 6.77, [
    '· Work와 검사 Detail을 물리 삭제하지 않는다.',
    '· 취소 상태에서 복원하지 않는다. 재진행은 신규예약을 생성한다.',
  ], { size: 9.5 });
}

module.exports = {
  title: 'P02-05  예약 조회   ·   P02-07  예약 취소',
  caption: '적용 정책: P02-05 CP-05, 상태 해석 / P02-07 CP-05, RP-10',
  draw,
};
