'use strict';
// 2 — P01 수검자 확인 / 관리 : P01 전체 프로세스 + P01-01 + P01-02 + P01-04(P01-05 포함) 통합
const { A, node, gate, term, sub, head, note, ar, elab, elabN, S } = require('../flow');

// 좌측 열(P01-01 · P01-04) 4레인
const LA = [0.60, 2.11, 3.62, 5.13], LW = 1.36;
const ax = i => LA[i], acx = i => LA[i] + LW / 2, ar_ = i => LA[i] + LW;
// 우측 열(P01-02) 4레인
const LB = [6.70, 8.28, 9.86, 11.44], BW = 1.42;
const bx = i => LB[i], bcx = i => LB[i] + BW / 2, br = i => LB[i] + BW;

const NS = { size: 8 };

function draw(c) {
  // ── P01 전체 프로세스 ────────────────────────────────────────────
  term(c, 0.60, 1.26, 1.90, 0.42, '수검자 확인 / 관리 시작', NS);
  ar(c, [[2.53, 1.47], [2.72, 1.47]]);
  gate(c, 2.75, 1.26, 1.20, 0.42, '업무 구분?', NS);
  ar(c, [[3.95, 1.47], [4.15, 1.47]], { arrow: false });
  c.line(4.15, 1.21, 4.15, 1.73, { stroke: S.C.ink, sw: S.W.ctrl });
  const BR = [
    ['조회 / 확인   →   P01-01 수검자 조회 및 확정', 1.10],
    ['신규 등록   →   P01-02 신규 수검자 등록', 1.36],
    ['정보 수정   →   P01-04 수검자 정보 수정', 1.62],
  ];
  BR.forEach(([t, y]) => {
    ar(c, [[4.15, y + 0.11], [4.37, y + 0.11]]);
    sub(c, 4.40, y, 3.60, 0.22, t, NS);
  });
  ar(c, [[8.00, 1.21], [8.15, 1.21], [8.15, 1.47], [8.27, 1.47]]);
  ar(c, [[8.00, 1.47], [8.27, 1.47]]);
  ar(c, [[8.00, 1.73], [8.15, 1.73], [8.15, 1.47], [8.27, 1.47]]);
  term(c, 8.30, 1.26, 2.10, 0.42, '수검자 확인 / 관리 종료', NS);
  note(c, 10.60, 1.10, 2.27, [
    '수검자 Master 삭제 프로세스는 정의하지 않는다.',
    '정보 오류는 P01-04로 수정한다. (EP-10)',
  ], { color: S.C.hint });

  // ── P01-01 수검자 조회 및 확정 ────────────────────────────────────
  head(c, A.x, 1.92, 6.03, 'P01-01  수검자 조회 및 확정', { h: 0.24 });
  const r = [2.26, 2.94, 3.62], H = 0.44;
  const cy = i => r[i] + H / 2;

  term(c, ax(0), r[0], LW, H, '수검자 확인 시작', NS);
  node(c, ax(1), r[0], LW, H, '조회조건 입력', NS);
  node(c, ax(2), r[0], LW, H, '수검자 Master 조회', NS);
  gate(c, ax(3), r[0], LW, H, '대상 수검자 존재?', NS);
  term(c, ax(1), r[1], LW, H, 'PatientId 확정', NS);
  node(c, ax(2), r[1], LW, H, '기존 수검자 선택', NS);
  term(c, ax(1), r[2], LW, H, '수검자 확인 중단', NS);
  gate(c, ax(2), r[2], LW, H, '신규등록 또는\n기존 수검자 확정?', NS);
  sub(c, ax(3), r[2], LW, H, 'P01-02\n신규 수검자 등록', NS);

  ar(c, [[ar_(0), cy(0)], [ax(1) - 0.03, cy(0)]]);
  ar(c, [[ar_(1), cy(0)], [ax(2) - 0.03, cy(0)]]);
  ar(c, [[ar_(2), cy(0)], [ax(3) - 0.03, cy(0)]]);
  // Yes → 기존 수검자 선택
  ar(c, [[acx(3) - 0.31, r[0] + H], [acx(3) - 0.31, 2.84], [acx(2), 2.84], [acx(2), r[1] - 0.03]]);
  elab(c, acx(3) - 0.11, 2.84, 'Yes');
  ar(c, [[ax(2), cy(1)], [ar_(1) + 0.03, cy(1)]]);
  // No → P01-02
  ar(c, [[acx(3) + 0.31, r[0] + H], [acx(3) + 0.31, r[2] - 0.03]]);
  elab(c, acx(3) + 0.31, 3.20, 'No');
  ar(c, [[ax(3), cy(2)], [ar_(2) + 0.03, cy(2)]]);
  ar(c, [[ax(2), cy(2)], [ar_(1) + 0.03, cy(2)]]);
  elabN(c, (ax(2) + ar_(1)) / 2, cy(2) - 0.15, 'No');
  // Yes → PatientId 확정
  ar(c, [[acx(2), r[2]], [acx(2), 3.50], [acx(1), 3.50], [acx(1), r[1] + H + 0.03]]);
  elab(c, acx(2) - 0.34, 3.50, 'Yes');

  // ── P01-04 수검자 정보 수정 (+ P01-05) ────────────────────────────
  head(c, A.x, 4.44, 6.03, 'P01-04  수검자 정보 수정   ·   P01-05  식별정보 변경 검증', { h: 0.24 });
  const q = [4.78, 5.285, 5.79, 6.295], QH = 0.36;
  const qy = i => q[i] + QH / 2;

  term(c, ax(0), q[0], LW, QH, '정보 수정 시작', NS);
  node(c, ax(1), q[0], LW, QH, '기존 수검자 선택 /\n최신 상세 조회', NS);
  gate(c, ax(2), q[0], LW, QH, '대상 존재?', NS);
  term(c, ax(3), q[0], LW, QH, '수정 대상 없음', NS);

  gate(c, ax(0), q[1], LW, QH, '변경 가능?', NS);
  sub(c, ax(1), q[1], LW, QH, 'P01-05\n식별정보 변경 검증', NS);
  gate(c, ax(2), q[1], LW, QH, '주민등록번호 또는\n차트번호 변경?', NS);
  node(c, ax(3), q[1], LW, QH, '수정값 입력', NS);

  node(c, ax(0), q[2], LW, QH, '필수값·형식·\n동시성 검증', NS);
  gate(c, ax(1), q[2], LW, QH, '저장 가능?', NS);
  node(c, ax(2), q[2], LW, QH, '수검자 정보 수정', NS);
  term(c, ax(3), q[2], LW, QH, '정보 수정 완료', NS);

  term(c, ax(1), q[3], LW, QH, '수정 불가 /\n기존값 유지', NS);
  // '활성 업무'와 P02의 '중복판단 유효예약'은 시점 기준이 다르다. 한쪽만 실으면 오독된다.
  note(c, ax(2), 6.18, 3.08, [
    'P01-05 = 차트번호·주민번호 고유성 검증',
    '+ 주민번호 변경 시 활성 업무 존재 → 변경 불가',
    '활성 업무 = 상태 RSV·RCP인 모든 업무 (예약일 시점 무관)',
  ], { color: S.C.hint, size: 7.5 });

  ar(c, [[ar_(0), qy(0)], [ax(1) - 0.03, qy(0)]]);
  ar(c, [[ar_(1), qy(0)], [ax(2) - 0.03, qy(0)]]);
  ar(c, [[ar_(2), qy(0)], [ax(3) - 0.03, qy(0)]]);
  elabN(c, (ar_(2) + ax(3)) / 2, qy(0) - 0.15, 'No');
  ar(c, [[acx(2), q[0] + QH], [acx(2), 5.21], [acx(3), 5.21], [acx(3), q[1] - 0.03]]);
  elab(c, acx(2) + 0.28, 5.21, 'Yes');
  ar(c, [[ax(3), qy(1)], [ar_(2) + 0.03, qy(1)]]);
  ar(c, [[ax(2), qy(1)], [ar_(1) + 0.03, qy(1)]]);
  elabN(c, (ax(2) + ar_(1)) / 2, qy(1) - 0.15, 'Yes');
  ar(c, [[ax(1), qy(1)], [ar_(0) + 0.03, qy(1)]]);
  // 식별정보 변경 없음 → 필수값 검증으로 직행
  ar(c, [[acx(2), q[1] + QH], [acx(2), 5.717], [acx(0) + 0.30, 5.717], [acx(0) + 0.30, q[2] - 0.03]]);
  elab(c, acx(2) - 0.30, 5.717, 'No');
  // 변경 가능 Yes → 필수값 검증
  ar(c, [[acx(0) - 0.30, q[1] + QH], [acx(0) - 0.30, q[2] - 0.03]]);
  elab(c, acx(0) - 0.30, 5.717, 'Yes');
  // 변경 불가 → 수정 불가 / 기존값 유지
  ar(c, [[ax(0), qy(1)], [0.50, qy(1)], [0.50, qy(3)], [ax(1) - 0.03, qy(3)]]);
  elab(c, 0.50, qy(1) + 0.30, 'No');
  ar(c, [[ar_(0), qy(2)], [ax(1) - 0.03, qy(2)]]);
  ar(c, [[ar_(1), qy(2)], [ax(2) - 0.03, qy(2)]]);
  elabN(c, (ar_(1) + ax(2)) / 2, qy(2) - 0.15, 'Yes');
  ar(c, [[ar_(2), qy(2)], [ax(3) - 0.03, qy(2)]]);
  ar(c, [[acx(1), q[2] + QH], [acx(1), q[3] - 0.03]]);
  elab(c, acx(1) + 0.22, (q[2] + QH + q[3]) / 2, 'No');

  // ── P01-02 신규 수검자 등록 ──────────────────────────────────────
  head(c, 6.70, 1.92, 6.16, 'P01-02  신규 수검자 등록', { h: 0.24 });
  const p = [2.26, 3.16, 4.06, 4.96, 5.86], PH = 0.52;
  const py = i => p[i] + PH / 2, pb = i => p[i] + PH;

  term(c, bx(0), p[0], BW, PH, '신규 수검자\n등록 시작', NS);
  node(c, bx(1), p[0], BW, PH, '이름 /\n주민등록번호 입력', NS);
  gate(c, bx(2), p[0], BW, PH, '필수값·형식 유효?', NS);
  node(c, bx(3), p[0], BW, PH, 'Birthday / Gender\n자동산출', NS);

  node(c, bx(2), p[1], BW, PH, '입력값 보완', NS);
  sub(c, bx(3), p[1], BW, PH, 'P01-03\n등록 중복 검증', NS);

  term(c, bx(1), p[2], BW, PH, '기존 수검자 확정 /\nPatientId 반환', NS);
  node(c, bx(2), p[2], BW, PH, '기존 수검자 확인', NS);
  gate(c, bx(3), p[2], BW, PH, '중복 검증 결과', NS);

  gate(c, bx(0), p[3], BW, PH, '저장 요청', NS);
  node(c, bx(1), p[3], BW, PH, '수동 차트번호 입력', NS);
  gate(c, bx(2), p[3], BW, PH, '자동발급?', NS);
  node(c, bx(3), p[3], BW, PH, '차트번호 방식 선택', NS);

  node(c, bx(0), p[4], BW, PH, '고유성·현재조건\n최종검증', NS);
  gate(c, bx(1), p[4], BW, PH, '저장 가능?', NS);
  node(c, bx(2), p[4], BW, PH, 'Patient Master 저장', NS);
  term(c, bx(3), p[4], BW, PH, '신규등록 완료 /\nPatientId·ChartNo 반환', NS);

  term(c, bx(1), 6.44, BW, 0.36, '등록 중단 또는 실패', NS);

  ar(c, [[br(0), py(0)], [bx(1) - 0.03, py(0)]]);
  ar(c, [[br(1), py(0)], [bx(2) - 0.03, py(0)]]);
  ar(c, [[br(2), py(0)], [bx(3) - 0.03, py(0)]]);
  elabN(c, (br(2) + bx(3)) / 2, py(0) - 0.18, 'Yes');
  ar(c, [[bcx(2), pb(0)], [bcx(2), p[1] - 0.03]]);
  elab(c, bcx(2) + 0.24, (pb(0) + p[1]) / 2, 'No');
  // 입력값 보완 → 이름 / 주민등록번호 입력
  ar(c, [[bx(2), py(1)], [bcx(1), py(1)], [bcx(1), pb(0) + 0.03]]);
  ar(c, [[bcx(3), pb(0)], [bcx(3), p[1] - 0.03]]);
  ar(c, [[bcx(3), pb(1)], [bcx(3), p[2] - 0.03]]);
  ar(c, [[bx(3), py(2)], [br(2) + 0.03, py(2)]]);
  elabN(c, (bx(3) + br(2)) / 2, p[2] - 0.14, '동일 주민번호');
  ar(c, [[bx(2), py(2)], [br(1) + 0.03, py(2)]]);
  ar(c, [[bcx(3), pb(2)], [bcx(3), p[3] - 0.03]]);
  elab(c, bcx(3), (pb(2) + p[3]) / 2, '신규등록 가능');
  ar(c, [[bx(3), py(3)], [br(2) + 0.03, py(3)]]);
  ar(c, [[bx(2), py(3)], [br(1) + 0.03, py(3)]]);
  elabN(c, (bx(2) + br(1)) / 2, py(3) - 0.18, 'No');
  ar(c, [[bx(1), py(3)], [br(0) + 0.03, py(3)]]);
  // 자동발급 Yes → 저장 요청 (행 위쪽으로 우회)
  ar(c, [[bcx(2), p[3]], [bcx(2), 4.77], [bcx(0), 4.77], [bcx(0), p[3] - 0.03]]);
  elab(c, bcx(2) - 0.32, 4.77, 'Yes');
  ar(c, [[bcx(0), pb(3)], [bcx(0), p[4] - 0.03]]);
  ar(c, [[br(0), py(4)], [bx(1) - 0.03, py(4)]]);
  ar(c, [[br(1), py(4)], [bx(2) - 0.03, py(4)]]);
  elabN(c, (br(1) + bx(2)) / 2, py(4) - 0.18, 'Yes');
  ar(c, [[br(2), py(4)], [bx(3) - 0.03, py(4)]]);
  ar(c, [[bcx(1), p[4] + PH], [bcx(1), 6.41]]);
  elab(c, bcx(1) + 0.22, 6.41, 'No');
}

module.exports = {
  title: 'P01  수검자 확인 / 관리',
  caption: '적용 정책: P01-01 EP-01, EP-02 / P01-02 EP-03, EP-04, EP-09 / P01-04 EP-04, EP-08, CP-06 / P01-05 EP-03, EP-05, EP-08',
  draw,
};
