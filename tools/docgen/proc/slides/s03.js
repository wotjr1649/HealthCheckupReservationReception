'use strict';
// 3 — P01-03 등록 중복 검증 : 주민번호 동일 / 이름+생년월일 후보 / 재입력·별도등록·중단 3분기
const { A, node, gate, term, head, note, ar, elab, elabN, S } = require('../flow');

const L = [0.90, 2.90, 4.90, 6.90], W = 1.70;
const cx = i => L[i] + W / 2, rr = i => L[i] + W;
const R = [1.15, 2.09, 3.03, 3.97, 4.91, 5.85], H = 0.52;
const cy = i => R[i] + H / 2, rb = i => R[i] + H;
const NS = { size: 9 };

function draw(c) {
  term(c, L[1], R[0], W, H, '중복 검증 시작', NS);
  gate(c, L[1], R[1], W, H, '동일 주민등록번호 존재?', NS);
  gate(c, L[0], R[2], W, H, '기존 이름과\n입력 이름 동일?', NS);
  gate(c, L[2], R[2], W, H, '이름+생년월일\n동일 후보 존재?', NS);
  node(c, L[0], R[3], W, H, '기존 수검자 확정', NS);
  node(c, L[1], R[3], W, H, '이름 불일치 확인 안내', NS);
  node(c, L[2], R[3], W, H, '중복 후보 목록 표시', NS);
  term(c, L[0], R[4], W, H, '기존 수검자', NS);
  gate(c, L[2], R[4], W, H, '사용자 확인', NS);
  term(c, L[3], R[4], W, H, '신규등록 가능', NS);
  node(c, L[1], R[5], W, H, '입력값 수정', NS);
  term(c, L[3], R[5], W, H, '등록 중단', NS);

  ar(c, [[cx(1), rb(0)], [cx(1), R[1] - 0.03]]);
  ar(c, [[cx(1) - 0.30, rb(1)], [cx(1) - 0.30, 2.82], [cx(0), 2.82], [cx(0), R[2] - 0.03]]);
  elab(c, cx(1) - 0.62, 2.82, 'Yes');
  ar(c, [[cx(1) + 0.30, rb(1)], [cx(1) + 0.30, 2.82], [cx(2), 2.82], [cx(2), R[2] - 0.03]]);
  elab(c, cx(1) + 0.62, 2.82, 'No');

  ar(c, [[cx(0), rb(2)], [cx(0), R[3] - 0.03]]);
  elab(c, cx(0) + 0.22, 3.76, 'Yes');
  ar(c, [[cx(0) + 0.42, rb(2)], [cx(0) + 0.42, 3.76], [cx(1), 3.76], [cx(1), R[3] - 0.03]]);
  elab(c, cx(0) + 0.74, 3.76, 'No');
  ar(c, [[cx(0), rb(3)], [cx(0), R[4] - 0.03]]);
  ar(c, [[cx(1), rb(3)], [cx(1), 4.70], [cx(0) + 0.42, 4.70], [cx(0) + 0.42, R[4] - 0.03]]);

  ar(c, [[cx(2), rb(2)], [cx(2), R[3] - 0.03]]);
  elab(c, cx(2) + 0.22, 3.76, 'Yes');
  ar(c, [[rr(2), cy(2)], [cx(3), cy(2)], [cx(3), R[4] - 0.03]]);
  elab(c, cx(3), cy(2) - 0.16, 'No');
  ar(c, [[cx(2), rb(3)], [cx(2), R[4] - 0.03]]);
  ar(c, [[rr(2), cy(4)], [L[3] - 0.03, cy(4)]]);
  elabN(c, (rr(2) + L[3]) / 2, R[4] - 0.16, '실제 별도 수검자');
  ar(c, [[cx(2), rb(4)], [cx(2), 5.64], [cx(3), 5.64], [cx(3), R[5] - 0.03]]);
  elab(c, cx(3) - 0.30, 5.64, '취소');
  ar(c, [[cx(2) - 0.42, rb(4)], [cx(2) - 0.42, 5.64], [cx(1), 5.64], [cx(1), R[5] - 0.03]]);
  elab(c, cx(2) - 0.86, 5.64, '주민번호 오입력');
  // 입력값 수정 → 중복 검증 시작 (좌측 여백으로 되돌림)
  ar(c, [[L[1], cy(5)], [0.62, cy(5)], [0.62, cy(0)], [L[1] - 0.03, cy(0)]]);

  // ── 우측: 적용 규칙 · 종료점 ─────────────────────────────────────
  const px = 8.90, pw = A.r - px;
  let y = head(c, px, 1.15, pw, '적용 규칙');
  const rules = [
    '최종 고유성 기준은 주민등록번호다.',
    '동일 주민등록번호는 이름이 달라도 신규등록하지 않는다.',
    '이름+생년월일 후보는 경고·확인 대상이지 자동 동일인 확정조건이 아니다.',
    '별도 수검자로 계속하기 확인은 현재 이름·생년월일·주민등록번호 조합에만 유효하다. 값이 바뀌면 다시 검증한다.',
    'UI 확인 이후에도 저장 Transaction에서 주민등록번호와 차트번호 고유성을 다시 검증한다.',
  ];
  const nb = note(c, px, y + 0.06, pw, rules.map(t => '· ' + t), { size: 9 });

  y = head(c, px, nb.b + 0.28, pw, '종료점');
  note(c, px, y + 0.06, pw, [
    '기존 수검자   —   동일 주민등록번호를 확인하고 기존 PatientId로 확정한다.',
    '신규등록 가능   —   후보가 없거나 별도 수검자로 확인되어 신규행을 만든다.',
    '등록 중단   —   사용자가 취소하여 신규행을 만들지 않는다.',
  ], { size: 9 });
}

module.exports = {
  title: 'P01-03  등록 중복 검증',
  caption: '적용 정책: P01-03 EP-05~07',
  draw,
};
