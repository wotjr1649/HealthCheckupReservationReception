    let maxCol = 0, rows = 0;
    ws.eachRow({ includeEmpty: false }, (row) => {
      rows++;
      row.eachCell({ includeEmpty: false }, (cell, col) => {
        if (col > maxCol) maxCol = col;
        if (cell.value !== null && cell.value !== undefined) all.push(String(cell.value));
      });
    });
    const v = (ws.views && ws.views[0]) || {};
