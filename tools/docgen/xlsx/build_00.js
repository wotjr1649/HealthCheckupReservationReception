const NAVY = 'FF1F3864';
const HEAD_FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: NAVY } };
const SUB_FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFD9D9D9' } };
const ZEBRA_FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF2F2F2' } };
const THIN = { style: 'thin', color: { argb: 'FFBFBFBF' } };
const BORDER = { top: THIN, left: THIN, bottom: THIN, right: THIN };

function build() {
  const wb = new ExcelJS.Workbook();
  wb.creator = '검진 예약·접수 업무 정책';
  wb.created = new Date();

  for (const s of SHEETS) {
    const ws = wb.addWorksheet(s.name, { views: [{ state: 'frozen', xSplit: 0, ySplit: 2 }] });
    const nCol = s.head.length;

    ws.columns = s.w.map((width) => ({ width }));

    // 1행: 제목
    const tRow = ws.getRow(1);
    tRow.getCell(1).value = s.title;
    tRow.getCell(1).font = { bold: true, size: 14, color: { argb: NAVY } };
    tRow.height = 26;

    // 2행: 표 머리글
    const hRow = ws.getRow(2);
    s.head.forEach((h, i) => {
      const c = hRow.getCell(i + 1);
      c.value = h;
      c.font = { bold: true, size: 11, color: { argb: 'FFFFFFFF' } };
      c.fill = HEAD_FILL;
      c.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
      c.border = BORDER;
    });
    hRow.height = 24;

    // 3행~: 데이터
    let r = 3;
    let prevGroup = null;
    let zebra = false;
    for (const row of s.rows) {
      if (row.g !== prevGroup) {
        if (prevGroup !== null) zebra = !zebra;
        prevGroup = row.g;
      }
      const xl = ws.getRow(r);
      xl.getCell(1).value = row.g;
      for (let i = 0; i < nCol - 1; i++) {
        xl.getCell(i + 2).value = row.a[i] === undefined ? '' : row.a[i];
      }
      for (let i = 1; i <= nCol; i++) {
        const c = xl.getCell(i);
        c.border = BORDER;
        const centered = row.k === 'h' || (row.ctr !== undefined && i - 2 >= row.ctr);
        c.alignment = { vertical: 'top', horizontal: centered ? 'center' : 'left', wrapText: true };
        if (row.k === 'h') {
          c.font = { bold: true, size: 10 };
          c.fill = SUB_FILL;
        } else {
          c.font = { size: 10 };
          if (zebra) c.fill = ZEBRA_FILL;
        }
      }
      // 구분 열은 항상 강조
      xl.getCell(1).font = { bold: true, size: 10, color: { argb: NAVY } };
      r++;
    }

    ws.autoFilter = { from: { row: 2, column: 1 }, to: { row: r - 1, column: nCol } };
  }

  return wb;
}

